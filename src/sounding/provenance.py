"""Data-policy enforcement: synthetic stimuli and public sources only.

The policy lives in docs/DATA_POLICY.md. This module is the part of it that a
machine can check, and the test suite runs it over every data file in the repo.
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from typing import Any

# The only ways a stimulus may come into existence.
ALLOWED_KINDS = frozenset(
    {
        "synthetic-handwritten",  # written by a project author, describing nobody
        "synthetic-template",  # assembled from handwritten parts by this package
        "synthetic-llm",  # generated by a model, then human-reviewed
    }
)

# Public documents the project may cite or draw categories from.
PUBLIC_SOURCES: dict[str, str] = {
    "FCA-FG21/1": (
        "FCA Finalised Guidance FG21/1, 'Guidance for firms on the fair treatment "
        "of vulnerable customers' (2021). Source of the four drivers of "
        "vulnerability: health, life events, resilience, capability."
    ),
    "FCA-PRIN2A": "FCA Handbook, PRIN 2A, the Consumer Duty.",
}

# Patterns that suggest real personal or account data. Deliberately conservative:
# a false positive costs a reworded sentence, a false negative costs the policy.
_PII_PATTERNS: dict[str, re.Pattern[str]] = {
    "email address": re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+"),
    "UK phone number": re.compile(r"(?:\+44\s?|\b0)\d{2,4}[\s-]?\d{3,4}[\s-]?\d{3,4}\b"),
    "National Insurance number": re.compile(
        r"\b[A-CEGHJ-PR-TW-Z]{2}\s?\d{2}\s?\d{2}\s?\d{2}\s?[A-D]\b"
    ),
    "UK postcode": re.compile(r"\b[A-Z]{1,2}\d[A-Z\d]?\s?\d[A-Z]{2}\b"),
    "sort code": re.compile(r"\b\d{2}-\d{2}-\d{2}\b"),
    "long digit run (account or card number)": re.compile(r"\b(?:\d[ -]?){8,19}\b"),
}


class DataPolicyError(ValueError):
    """Raised when a record breaks the synthetic-and-public-only policy."""


def find_pii(text: str) -> list[str]:
    """Return the names of any personal-data patterns found in ``text``."""
    return [name for name, pattern in _PII_PATTERNS.items() if pattern.search(text)]


def validate_record(record: Mapping[str, Any]) -> None:
    """Check one stimulus record. Raises ``DataPolicyError`` on any breach."""
    provenance = record.get("provenance")
    if not isinstance(provenance, Mapping):
        raise DataPolicyError("record has no provenance block")
    kind = provenance.get("kind")
    if kind not in ALLOWED_KINDS:
        raise DataPolicyError(f"provenance kind {kind!r} is not an allowed synthetic kind")
    for ref in provenance.get("sources", []):
        if ref not in PUBLIC_SOURCES:
            raise DataPolicyError(f"source {ref!r} is not in the public-source registry")
    hits = find_pii(str(record.get("text", "")))
    if hits:
        raise DataPolicyError(f"text looks like it contains personal data: {', '.join(hits)}")
